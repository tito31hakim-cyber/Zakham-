/// تنظيف نصوص ردود المستشار والعملاء قبل عرضها.
///
/// يزيل رموز Markdown الخام التي قد ترد من أي مصدر — نص خام من المزوّد،
/// أو قالب خادمي قديم — مع الحفاظ على فواصل الأسطر وبنية الفقرات حتى
/// يبقى النص مقروءاً بوضوح. لا يغيّر محتوى النص نفسه: لا يحذف كلمات
/// ولا يعيد صياغة، بل يزيل الرموز فقط.
///
/// القاعدة الدائمة (2026-11-19): أي رد معروض في واجهة التطبيق يمر
/// بهذه الدالة — حتى لو ورد نص خام من أي مصدر — فلا تصل رموز
/// Markdown الخام إلى المستخدم أبداً.
String sanitizeChatText(String input) {
  final out = <String>[];
  for (final raw in input.split('\n')) {
    // سطر فاصل في جدول Markdown (|---|---|) أو خط أفقي (---):
    // مكوّن من الأنابيب والشرطات والنقطتين والفراغات فقط — يُحذف.
    if (RegExp(r'^\s*[|:\s-]+$').hasMatch(raw) &&
        RegExp(r'[|-]').hasMatch(raw)) {
      continue;
    }
    // علامتا التأكيد ** وعلامات الكود ` تُحذف، والأنابيب | تصير فراغاً.
    var line = raw.replaceAll('**', '').replaceAll('`', '');
    line = line.replaceAll('|', ' ');
    // علامات عناوين Markdown في بداية السطر (# ## ### ...) تُحذف.
    line = line.replaceFirst(RegExp(r'^\s*#{1,6}\s*'), '');
    // فراغات متكررة داخل السطر تُدمج، وفراغات الأطراف تُحذف.
    line = line.replaceAll(RegExp(r' {2,}'), ' ').trim();
    out.add(line);
  }
  // أسطر فارغة متتالية تُدمج في سطر فارغ واحد كحد أقصى، وفراغات
  // بداية النص ونهايته تُحذف — فتبقى الفقرات كما هي.
  return out.join('\n').replaceAll(RegExp(r'\n{3,}'), '\n\n').trim();
}
